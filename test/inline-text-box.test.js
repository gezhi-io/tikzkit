import assert from "node:assert/strict";
import test from "node:test";
import { normalizeTikzText } from "../src/tikz/text.js";
import { layoutNativeTextRun } from "../src/tex/textBox.js";
import { tikzToSvg, tikzToSvgAsync } from "../src/index.js";

const gene = String.raw`\tt \textcolor{blue}{GUG}\textcolor{green}{CAU}\tikz[baseline]{\node[rectangle,fill=red,inner sep=.3mm,anchor=base]{\textcolor{white}{UAG}};}`;
const stop = String.raw`\tikz[baseline]{\node[rectangle,fill=red,inner sep=.3mm,anchor=base]{\textcolor{white}{\tt STOP}};}`;
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < .001, `${actual} vs MacTeX ${expected} pt`);

test("inline colored rectangles retain the original text, font and padding", () => {
  const normalized = normalizeTikzText(stop);
  assert.equal(normalized.inlineNodes?.length, 1);
  assert.equal(normalized.inlineNodes[0].text, String.raw`\textcolor{white}{\tt STOP}`);
  assert.deepEqual(normalized.inlineNodes[0].paddingX, { value: .3, unit: "mm" });
});

test("inline colored hboxes match independent MacTeX width, height and depth", () => {
  // Generated by fixtures/inline-text-box-metrics.tex, not renderer snapshots.
  for (const [source, width, height, depth] of [
    [gene, 48.95673, 6.96469, .85358],
    [stop, 22.70697, 6.96469, .85358],
    [String.raw`\tt A\tikz[baseline]{\node[rectangle,fill=red,inner xsep=2pt,inner ysep=1pt,anchor=base]{\textcolor{white}{gp}};}B`, 24.99982, 6.11111, 3.22223],
    [String.raw`\tt A\tikz[baseline]{\node[rectangle,fill=red,inner sep=1pt]{\textcolor{white}{gp}};}B`, 22.99982, 6.11111, 4.26389],
    [String.raw`\tt A\tikz[baseline]{\node[rectangle,fill=red,anchor=base]{\textcolor{white}{gp}};}B`, 27.999, 7.80513, 5.72182]
  ]) {
    const box = layoutNativeTextRun(normalizeTikzText(source), { family: "serif", sizePt: 10 });
    assert.ok(box, "supported inline picture must retain its hbox");
    close(box.width, width);
    close(box.height, height);
    close(box.depth, depth);
    const background = box.items.find(item => item.type === "rule");
    for (const glyph of box.items.filter(item => item.color === "white")) {
      assert.equal(glyph.family, "TikZKitMath_Typewriter");
      assert.ok(glyph.x >= background.x && glyph.x + 5.24996 <= background.x + background.width);
      assert.ok(glyph.y >= background.y && glyph.y <= background.y + background.height);
    }
  }
});

test("inline text is measured and painted identically in synchronous and browser paths", async () => {
  for (const mathRenderer of [undefined, "svg-text"]) {
    const source = `\\begin{tikzpicture}\\node[draw,anchor=base west,inner sep=0pt,outer sep=0pt] (n) {${gene}};\\end{tikzpicture}`;
    const sync = tikzToSvg(source, { mathRenderer });
    const asyncResult = await tikzToSvgAsync(source, { mathRenderer });
    for (const result of [sync, asyncResult]) {
      assert.deepEqual(result.diagnostics, []);
      const node = result.ir.items.find(item => item.type === "nodeBox");
      close(node.width * 72.27 / 2.54, 48.95673);
      close(node.height * 72.27 / 2.54, 7.81827);
      assert.match(result.svg, /class="tikz-text-native"/);
      const [, baseline] = result.svg.match(/class="tikz-text-native"[^>]*transform="translate\([^ ]+ ([-\d.]+)\)/);
      assert.ok(Math.abs(Number(baseline)) < .001);
    }
  }
});

test("unsupported inline transformations and mathematics retain their fallback", () => {
  for (const source of [
    String.raw`\tikz[scale=2,baseline]{\node[fill=red]{x};}`,
    String.raw`\tikz[baseline]{\node[fill=red,rotate=30]{x};}`,
    String.raw`\tikz[baseline]{\node[fill=red]{$x^2$};}`
  ]) assert.equal(layoutNativeTextRun(normalizeTikzText(source), { sizePt: 10 }), null);
});
