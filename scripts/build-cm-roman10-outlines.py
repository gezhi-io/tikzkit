"""Extract baseline-relative SVG paths from the packaged TikZKitCMR10 WOFF."""

import argparse
import hashlib
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "web/fonts/TikZKitCMR10-Regular.woff"
OUTPUT = ROOT / "src/fonts/cmRoman10Outlines.js"


def generate():
    rows, aliases, canonical = [], [], {}
    with TTFont(FONT) as font:
        if font["name"].getDebugName(1) != "TikZKitCMR10" or font["head"].unitsPerEm != 1000:
            raise ValueError("Expected the TikZKitCMR10 face at 1000 units/em")
        cmap = font.getBestCmap()
        if not cmap or any(t.isUnicode() and not t.cmap.items() <= cmap.items()
                           for t in font["cmap"].tables):
            raise ValueError("Expected a single unambiguous Unicode mapping")
        glyphs = font.getGlyphSet()
        for cp, name in sorted(cmap.items()):
            if name == ".notdef":
                continue
            pen = SVGPathPen(glyphs)
            glyphs[name].draw(pen)
            path = pen.getCommands()
            if not path:
                continue
            key = json.dumps(chr(cp), ensure_ascii=True)
            if path in canonical:
                aliases.append(f"paths[{key}] = paths[{canonical[path]}];")
            else:
                canonical[path] = key
                rows.append(f"  {key}: {json.dumps(path)},")

    return "\n".join([
        "// Generated by python3 scripts/build-cm-roman10-outlines.py; do not hand-edit.",
        "// Source: web/fonts/TikZKitCMR10-Regular.woff",
        f"// WOFF SHA-256: {hashlib.sha256(FONT.read_bytes()).hexdigest()}",
        "/*! Outlines copyright (c) 1997, 2009, American Mathematical Society. All Rights Reserved.",
        " * SPDX-License-Identifier: OFL-1.1",
        " * Full notice and license: ../../web/fonts/OFL-AMSFonts.txt */",
        "",
        "const paths = {",
        "  __proto__: null,",
        *rows, "};", "", *aliases, "",
        "/** One mapped glyph, 1000 units/em, baseline at y=0, y up; no shaping or fallback. */",
        "export function cmRoman10GlyphPath(text) {",
        '  return typeof text === "string" ? paths[text] ?? null : null;',
        "}", "",
    ]).encode("ascii")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the module without writing it")
    args = parser.parse_args()
    data = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != data:
            parser.exit(1, "Outline module is out of date; rerun without --check.\n")
    else:
        OUTPUT.write_bytes(data)
    print(f"{OUTPUT.relative_to(ROOT)}: {len(data)} bytes")
